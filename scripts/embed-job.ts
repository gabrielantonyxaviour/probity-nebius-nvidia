// Generates engine/src/ops/rails-prompts.generated.ts from job/config/prompts.yml. Run after editing the prompts: node scripts/embed-job.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// The two self-check prompts are written once, in job/config/prompts.yml, and generated into the Worker so the in-app rails
// and the NeMo Guardrails job use identical text. Parses only the shape that file has: "- task:", "max_tokens:", "content: |-".
const prompts: Record<string, { maxTokens: number; content: string }> = {};
const lines = readFileSync(join(root, "job/config/prompts.yml"), "utf8").split("\n");
for (let i = 0; i < lines.length; i++) {
  const m = /^ {2}- task: (\w+)/.exec(lines[i] ?? "");
  if (!m?.[1]) continue;
  let maxTokens = 64;
  let j = i + 1;
  const block: string[] = [];
  for (; j < lines.length && !/^ {2}- task:/.test(lines[j] ?? ""); j++) {
    const l = lines[j] ?? "";
    const mt = /^ {4}max_tokens: (\d+)/.exec(l);
    if (mt?.[1]) maxTokens = Number(mt[1]);
    if (/^ {6}/.test(l) || (block.length > 0 && l.trim() === "")) block.push(l.slice(6));
  }
  prompts[m[1]] = { maxTokens, content: block.join("\n").trim() };
}
if (!prompts.self_check_input || !prompts.self_check_output) throw new Error("prompts.yml must define self_check_input and self_check_output");
writeFileSync(join(root, "engine/src/ops/rails-prompts.generated.ts"), `// GENERATED by scripts/embed-job.ts from job/config/prompts.yml. Do not edit.\nexport const RAILS_PROMPTS = ${JSON.stringify(prompts, null, 1)} as const;\n`);
process.stdout.write("generated engine/src/ops/rails-prompts.generated.ts\n");
