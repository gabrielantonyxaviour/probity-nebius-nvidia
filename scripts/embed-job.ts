// Embeds the Nebius job's files into engine/src/ops/job-files.generated.ts so the Worker can inject them (no bundler rules needed).
// Run after editing anything in job/: node scripts/embed-job.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = ["run.sh", "sweep.py", "testset.json", "config/config.yml", "config/prompts.yml"];
const out: Record<string, string> = {};
for (const f of files) {
  const text = readFileSync(join(root, "job", f), "utf8");
  const bytes = Buffer.byteLength(text);
  if (bytes > 64 * 1024) throw new Error(`${f} is ${bytes} bytes; Nebius injects at most 64 KiB per file`);
  out[`/opt/probity/${f}`] = text;
}
const body = `// GENERATED by scripts/embed-job.ts from job/. Do not edit.\nexport const JOB_FILES: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(join(root, "engine/src/ops/job-files.generated.ts"), body);
process.stdout.write(`embedded ${files.length} files (${Object.values(out).reduce((n, t) => n + Buffer.byteLength(t), 0)} bytes)\n`);
