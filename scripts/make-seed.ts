// Builds engine/seed/seed.sql from engine/seed/data/*.json (synthetic payer: vendor master, AP, payment runs)
// and fixtures/requests/*/request.json (the inbox). Run: node scripts/make-seed.ts
// Idempotent output: every row is INSERT OR REPLACE, and applying it never touches runs, usage or sweep tables.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type Row = Record<string, unknown>;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = (n: string): Row[] => JSON.parse(readFileSync(join(root, "engine/seed/data", `${n}.json`), "utf8")) as Row[];
const q = (v: unknown): string => (v === null || v === undefined || v === "" ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const cents = (usd: unknown): number => Math.round(Number(usd) * 100);
const out: string[] = ["-- GENERATED by scripts/make-seed.ts. Do not edit.", "PRAGMA foreign_keys = OFF;"];

function emit(table: string, cols: string[], rows: unknown[][]): void {
  for (let i = 0; i < rows.length; i += 25) {
    const chunk = rows.slice(i, i + 25).map((r) => `(${r.map(q).join(", ")})`).join(",\n  ");
    out.push(`INSERT OR REPLACE INTO ${table} (${cols.join(", ")}) VALUES\n  ${chunk};`);
  }
}
const pick = (rows: Row[], cols: string[]): unknown[][] => rows.map((r) => cols.map((c) => r[c]));
const vcols = ["vendor_id", "legal_name", "legal_name_norm", "is_fictional", "uei", "registrant_cik", "remit_line1", "remit_unit", "remit_city", "remit_state", "remit_zip", "status", "merged_into", "legacy_vendor_no", "created_at"];

const vendors = data("vendor").map((v) => ({ ...v, is_fictional: v.is_fictional ? 1 : 0 }));
emit("vendors", vcols, pick(vendors, vcols));
const bcols = ["bank_account_id", "vendor_id", "bank_name", "routing", "account_last4", "account_hash", "status", "changed_at", "source_request_id"];
emit("vendor_bank_accounts", bcols, pick(data("vendor_bank_account"), bcols));
const ccols = ["contact_id", "vendor_id", "kind", "value", "valid_from", "valid_to", "changed_via"];
emit("vendor_contacts", ccols, pick(data("vendor_contact"), ccols));
emit("vendor_domains", ["vendor_id", "domain", "added_at"], pick(data("vendor_domain"), ["vendor_id", "domain", "added_at"]));
const rcols = ["remit_id", "vendor_id", "line1", "unit", "city", "state", "zip", "valid_from", "valid_to", "changed_via", "source_request_id"];
emit("vendor_remit_history", rcols, pick(data("vendor_remit_history"), rcols));
const lcols = ["log_id", "vendor_id", "request_id", "purpose", "phone_e164", "phone_source", "outcome", "called_at", "called_by"];
emit("vendor_contact_log", lcols, pick(data("vendor_contact_log"), lcols));
const hcols = ["request_id", "vendor_id", "claimed_name", "new_routing", "new_account_last4", "new_account_hash", "sender_domain", "letter_phones", "received_at", "requested_effective", "channel", "status"];
emit("bank_change_history", hcols, pick(data("bank_change_request"), hcols));

// Payment runs: cut-off is 14:00 US Eastern (EDT until 1 Nov 2026, EST after).
const cutoff = (date: string): string => `${date}T${date < "2026-11-01" ? "18" : "19"}:00:00Z`;
const runs = data("payment_run");
emit("payment_runs", ["payment_run_id", "scheduled_date", "cutoff_at", "status"], runs.map((r) => [r.payment_run_id, r.scheduled_date, cutoff(String(r.scheduled_date)), r.status]));

const invoices = data("ap_invoice").map((i) => ({ ...i, amount_cents: cents(i.amount_usd) }));
const items = data("payment_run_item").map((i) => ({ ...i, amount_cents: cents(i.amount_usd) }));

// Inbox requests
const fixDir = join(root, "fixtures/requests");
type Req = { requestId: string; vendorId: string; kind: string; receivedAt: string; senderEmail: string; paymentRunId: string; claimedName: string; channel: string; changeKinds: string[]; candidateVendorIds: string[]; email: Row; hasEml: boolean };
const reqs: Req[] = readdirSync(fixDir).sort().map((d) => JSON.parse(readFileSync(join(fixDir, d, "request.json"), "utf8")) as Req);
const activeAccount = (vid: string): Row | undefined => data("vendor_bank_account").find((b) => b.vendor_id === vid && b.status === "active");

const rows: unknown[][] = [];
for (const r of reqs) {
  let atRisk = items.filter((i) => i.payment_run_id === r.paymentRunId && i.vendor_id === r.vendorId).reduce((s, i) => s + i.amount_cents, 0);
  if (atRisk === 0) {
    // Vendor has no line in that run yet: its approved and scheduled invoices would be swept into it.
    const open = invoices.filter((i) => i.vendor_id === r.vendorId && ["approved", "scheduled", "open"].includes(String(i.status)));
    atRisk = open.reduce((s, i) => s + i.amount_cents, 0);
  }
  if (atRisk === 0) {
    // Nothing queued for this vendor: add one approved invoice and its payment-run line so the request has money at risk.
    const amount = 1184250 + ((Number(r.requestId.slice(-3)) * 7919) % 53000) * 17;
    const invNo = `INV-${r.vendorId.slice(2)}-${r.requestId.slice(-4)}`;
    const acct = activeAccount(r.vendorId);
    invoices.push({ invoice_no: invNo, vendor_id: r.vendorId, amount_cents: amount, invoice_date: "2026-10-12", status: "approved" } as Row);
    items.push({ item_id: `PRI-X${r.requestId.slice(-4)}`, payment_run_id: r.paymentRunId, vendor_id: r.vendorId, invoice_no: invNo, bank_account_id: String(acct?.bank_account_id ?? ""), amount_cents: amount } as Row);
    atRisk = amount;
  }
  const run = runs.find((x) => x.payment_run_id === r.paymentRunId);
  if (!run) throw new Error(`unknown payment run ${r.paymentRunId}`);
  const json = { claimedName: r.claimedName, channel: r.channel, changeKinds: r.changeKinds, candidateVendorIds: r.candidateVendorIds, paymentRunId: r.paymentRunId, email: r.email };
  rows.push([r.requestId, r.vendorId, r.kind, r.receivedAt, r.senderEmail, atRisk, cutoff(String(run.scheduled_date)), "unchecked", null, null, null, 1, `${r.requestId}.letter.pdf`, r.hasEml ? `${r.requestId}.headers.eml` : null, JSON.stringify(json)]);
}
emit("ap_invoices", ["invoice_no", "vendor_id", "amount_cents", "invoice_date", "status"], pick(invoices, ["invoice_no", "vendor_id", "amount_cents", "invoice_date", "status"]));
emit("payment_run_items", ["item_id", "payment_run_id", "vendor_id", "invoice_no", "bank_account_id", "amount_cents"], pick(items, ["item_id", "payment_run_id", "vendor_id", "invoice_no", "bank_account_id", "amount_cents"]));
// A re-seed must not reset a request that has already been checked: keep its state columns.
out.push(`-- inbox requests (state columns are reset only on first insert)`);
for (const row of rows) {
  const [id, vendor, kind, recv, sender, amt, next, , , , , syn, lk, ek, js] = row;
  out.push(`INSERT INTO requests (id, vendor_id, kind, received_at, sender_email, amount_cents, next_run_at, synthetic, letter_key, eml_key, json) VALUES (${[id, vendor, kind, recv, sender, amt, next, syn, lk, ek, js].map(q).join(", ")})
  ON CONFLICT(id) DO UPDATE SET vendor_id=excluded.vendor_id, kind=excluded.kind, received_at=excluded.received_at, sender_email=excluded.sender_email, amount_cents=excluded.amount_cents, next_run_at=excluded.next_run_at, letter_key=excluded.letter_key, eml_key=excluded.eml_key, json=excluded.json;`);
}
out.push(`INSERT OR IGNORE INTO settings (key, value) VALUES ('stopped', '0');`);
const target = join(root, "engine/seed/seed.sql");
writeFileSync(target, out.join("\n") + "\n");
if (!existsSync(target)) throw new Error("seed not written");
process.stdout.write(`seed.sql: ${vendors.length} vendors, ${items.length} run items, ${rows.length} requests\n`);
for (const r of reqs) process.stdout.write(`  ${r.requestId} ${r.vendorId} ${r.paymentRunId} ${(rows.find((x) => x[0] === r.requestId)![5] as number) / 100}\n`);
